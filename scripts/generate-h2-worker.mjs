// The worker of `http2Worker` runs from a string, and that string must hold
// the same session code as the main thread. This script compiles
// `src/core/h2-worker-thread.ts` and `src/core/h2.ts` to CommonJS and writes
// them as one string to `src/core/h2-worker-source.ts`. With `--check` it
// writes nothing, and fails when that file is not up to date.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const target = join(root, "src/core/h2-worker-source.ts");
const out = mkdtempSync(join(tmpdir(), "ukc-h2-worker-"));

let source;
try {
  execFileSync(
    process.execPath,
    [
      join(root, "node_modules/typescript/bin/tsc"),
      "--ignoreConfig",
      "src/core/h2-worker-thread.ts",
      ...["--module", "commonjs", "--moduleResolution", "bundler", "--target", "es2022"],
      ...["--types", "node", "--rootDir", "src", "--outDir", out],
      // `npm run typecheck` checks the types of the two files.
      ...["--removeComments", "--noCheck"],
    ],
    { cwd: root, stdio: "inherit" },
  );
  const compiled = (name) => readFileSync(join(out, "core", name), "utf8").trimEnd();
  source = [
    "const h2 = {};",
    "((exports) => {",
    compiled("h2.js"),
    "})(h2);",
    "((require) => {",
    compiled("h2-worker-thread.js"),
    '})((id) => (id === "./h2.js" ? h2 : require(id)));',
  ].join("\n");
} finally {
  rmSync(out, { recursive: true, force: true });
}

const escaped = source.replace(/[\\`]|\$\{/g, (match) => `\\${match}`);
const file = `// SPDX-License-Identifier: BSD-3-Clause
// Copyright (c) 2026, Unikraft GmbH.

// Generated by scripts/generate-h2-worker.mjs from h2-worker-thread.ts and
// h2.ts. Do not edit.

export const WORKER_SOURCE = \`${escaped}\`;
`;

if (!process.argv.includes("--check")) {
  writeFileSync(target, file);
} else if (readFileSync(target, "utf8") !== file) {
  console.error(
    "src/core/h2-worker-source.ts is not up to date. Run `npm run generate:worker` and commit the result.",
  );
  process.exit(1);
}
